"""Paired C1-C5 bootstrap analysis for train_ablation.py outputs.

Expected input: per-run *_evaluation.csv files generated by train_ablation.py.

The analysis explicitly intersects condition pairs by (topology, seed), so
a result is never treated as paired merely because two arrays happen to have
the same length.

Primary comparison:
  C2-C1  centralized critic effect
  C3-C2  spatial coordination effect
  C3-C5  capacity-control isolation
  C4-C3  VQ compression cost
  C4-C2  total proposed gain

For each pair the script reports paired mean difference, bootstrap 95% CI,
and an empirical two-sided sign-based bootstrap p-value.
"""
from __future__ import annotations

import argparse
import glob
import os

import numpy as np
import pandas as pd


CHAINS = [
    ("C2 vs C1 (centralized critic effect)", "C2", "C1"),
    ("C3 vs C2 (spatial coordination effect)", "C3", "C2"),
    ("C3 vs C5 (capacity-control isolation)", "C3", "C5"),
    ("C4 vs C3 (VQ compression cost)", "C4", "C3"),
    ("C4 vs C2 (total proposed gain)", "C4", "C2"),
]

PRIMARY_METRICS = [
    "throughput_packets",
    "blocked_events_per_step",
    "backhaul_bits_per_step",
    "overlap_sta_selections_eval",
    "overlap_sta_final_queue_sum",
    "fairness_mean",
]


def bootstrap_paired_ci(
    data_a,
    data_b,
    n_bootstraps=10000,
    ci=95,
    seed=42,
):
    """Return mean paired difference, percentile CI and two-sided p-value."""
    a = np.asarray(data_a, dtype=float)
    b = np.asarray(data_b, dtype=float)
    if len(a) != len(b):
        raise ValueError("Paired arrays must have equal length.")
    if len(a) == 0:
        raise ValueError("No paired observations.")
    if len(a) == 1:
        diff = float(a[0] - b[0])
        return diff, diff, diff, np.nan, False

    diffs = a - b
    rng = np.random.default_rng(seed)
    samples = rng.choice(diffs, size=(n_bootstraps, len(diffs)), replace=True)
    boot_means = samples.mean(axis=1)

    alpha = (100.0 - ci) / 2.0
    lower = float(np.percentile(boot_means, alpha))
    upper = float(np.percentile(boot_means, 100.0 - alpha))
    mean_diff = float(np.mean(diffs))

    # Two-sided bootstrap tail probability around zero.
    p_value = float(
        2.0 * min(
            np.mean(boot_means <= 0.0),
            np.mean(boot_means >= 0.0),
        )
    )
    p_value = min(max(p_value, 1.0 / n_bootstraps), 1.0)
    significant = bool(lower > 0.0 or upper < 0.0)
    return mean_diff, lower, upper, p_value, significant


def load_evaluation_rows(results_dir):
    pattern = os.path.join(results_dir, "*_evaluation.csv")
    files = sorted(glob.glob(pattern))
    if not files:
        raise FileNotFoundError(
            f"No '*_evaluation.csv' files found in {results_dir}"
        )

    frames = []
    for path in files:
        frame = pd.read_csv(path)
        frame["_source_file"] = os.path.basename(path)
        frames.append(frame)

    df = pd.concat(frames, ignore_index=True)

    required = {
        "topology", "condition_id", "seed",
        "throughput_packets", "blocked_events_per_step",
        "backhaul_bits_per_step",
    }
    missing = required - set(df.columns)
    if missing:
        raise ValueError(
            "Evaluation CSV is missing required columns: "
            + ", ".join(sorted(missing))
        )

    df["condition_id"] = df["condition_id"].astype(str)
    df["seed"] = pd.to_numeric(df["seed"], errors="raise").astype(int)

    # Prevent accidental duplicate run records from silently entering a pair.
    key = ["topology", "condition_id", "seed"]
    duplicates = df[df.duplicated(key, keep=False)]
    if not duplicates.empty:
        names = duplicates[key].drop_duplicates().to_dict("records")
        raise ValueError(
            "Duplicate evaluation records detected for "
            "(topology, condition_id, seed): " + str(names)
        )

    return df


def numeric_condition_summary(df):
    rows = []
    for (topology, condition), group in df.groupby(
        ["topology", "condition_id"], sort=True
    ):
        row = {
            "topology": topology,
            "condition_id": condition,
            "n_seeds": int(group["seed"].nunique()),
        }
        for metric in PRIMARY_METRICS:
            if metric not in group.columns:
                continue
            values = pd.to_numeric(group[metric], errors="coerce").dropna()
            if len(values) == 0:
                row[f"{metric}_mean"] = ""
                row[f"{metric}_std"] = ""
            else:
                row[f"{metric}_mean"] = float(values.mean())
                row[f"{metric}_std"] = (
                    float(values.std(ddof=1)) if len(values) > 1 else 0.0
                )
        rows.append(row)
    return pd.DataFrame(rows)


def paired_frame(df, condition_a, condition_b, metric):
    needed = ["topology", "seed", metric]
    if metric not in df.columns:
        return pd.DataFrame()

    a = df[df["condition_id"] == condition_a][needed].copy()
    b = df[df["condition_id"] == condition_b][needed].copy()

    a[metric] = pd.to_numeric(a[metric], errors="coerce")
    b[metric] = pd.to_numeric(b[metric], errors="coerce")

    a = a.rename(columns={metric: "a_value"})
    b = b.rename(columns={metric: "b_value"})

    merged = a.merge(
        b, on=["topology", "seed"], how="inner", validate="one_to_one"
    )
    return merged.dropna(subset=["a_value", "b_value"])


def run_analysis(
    results_dir="./results_csv",
    output_dir=None,
    n_bootstraps=10000,
    bootstrap_seed=42,
):
    df = load_evaluation_rows(results_dir)

    print("=" * 90)
    print("[1] Loaded evaluation runs")
    print("=" * 90)
    print(
        f"files={df['_source_file'].nunique()} | rows={len(df)} | "
        f"topologies={df['topology'].nunique()} | "
        f"conditions={sorted(df['condition_id'].unique())} | "
        f"seeds={sorted(df['seed'].unique())}"
    )

    summary_df = numeric_condition_summary(df)
    print("\n[2] Condition-level evaluation summary")
    print("=" * 90)
    print(summary_df.to_string(index=False))

    paired_rows = []
    pair_counts = []

    for label, cond_a, cond_b in CHAINS:
        for topology in sorted(df["topology"].unique()):
            topo_df = df[df["topology"] == topology]

            for metric in PRIMARY_METRICS:
                if metric not in df.columns:
                    continue

                pair = paired_frame(topo_df, cond_a, cond_b, metric)
                if pair.empty:
                    continue

                diffs = pair["a_value"].to_numpy() - pair["b_value"].to_numpy()
                mean_d, ci_l, ci_u, p_value, significant = (
                    bootstrap_paired_ci(
                        pair["a_value"].to_numpy(),
                        pair["b_value"].to_numpy(),
                        n_bootstraps=n_bootstraps,
                        seed=bootstrap_seed,
                    )
                )

                pair_counts.append({
                    "topology": topology,
                    "comparison": label,
                    "condition_a": cond_a,
                    "condition_b": cond_b,
                    "metric": metric,
                    "n_pairs": len(pair),
                    "paired_seeds": ",".join(
                        str(x) for x in sorted(pair["seed"].unique())
                    ),
                })

                paired_rows.append({
                    "topology": topology,
                    "comparison": label,
                    "condition_a": cond_a,
                    "condition_b": cond_b,
                    "metric": metric,
                    "n_pairs": len(pair),
                    "mean_diff_A_minus_B": mean_d,
                    "ci95_lower": ci_l,
                    "ci95_upper": ci_u,
                    "bootstrap_p_value": p_value,
                    "significant_ci95": significant,
                })

    paired_df = pd.DataFrame(paired_rows)
    pairs_df = pd.DataFrame(pair_counts)

    print("\n[3] Explicit same-seed paired bootstrap")
    print("=" * 90)
    if paired_df.empty:
        print("No complete condition pairs were found.")
    else:
        display_cols = [
            "topology", "comparison", "metric", "n_pairs",
            "mean_diff_A_minus_B", "ci95_lower", "ci95_upper",
            "bootstrap_p_value", "significant_ci95",
        ]
        print(paired_df[display_cols].to_string(index=False))

    if output_dir is None:
        output_dir = results_dir
    os.makedirs(output_dir, exist_ok=True)

    summary_path = os.path.join(output_dir, "evaluation_condition_summary.csv")
    paired_path = os.path.join(output_dir, "paired_bootstrap_results.csv")
    pairs_path = os.path.join(output_dir, "paired_seed_manifest.csv")

    summary_df.to_csv(summary_path, index=False, encoding="utf-8-sig")
    paired_df.to_csv(paired_path, index=False, encoding="utf-8-sig")
    pairs_df.to_csv(pairs_path, index=False, encoding="utf-8-sig")

    print("\n[4] Analysis files")
    print("=" * 90)
    print(summary_path)
    print(paired_path)
    print(pairs_path)

    return summary_df, paired_df, pairs_df


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results-dir", default="./results_csv")
    parser.add_argument("--output-dir", default=None)
    parser.add_argument("--bootstraps", type=int, default=10000)
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    run_analysis(
        results_dir=args.results_dir,
        output_dir=args.output_dir,
        n_bootstraps=args.bootstraps,
        bootstrap_seed=args.seed,
    )


if __name__ == "__main__":
    main()
