"""
experiments/make_random_topologies.py
Writes configs/topologies_random.yaml: R000-R199 (stage 1, baselines) and L00-L19 (stage 2,
learners), each set a Latin hypercube over the design variables of src/envs/random_topology.py.

    python experiments/make_random_topologies.py
"""
from __future__ import annotations

import os
import sys

import yaml

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from src.envs.random_topology import RANGES, build_spec, design_points

SETS = {"R": (200, 2026), "L": (20, 2027)}  # prefix: (count, design seed)
OUT = "configs/topologies_random.yaml"


def main() -> None:
    topologies, groups = {}, {}
    for prefix, (count, seed) in SETS.items():
        width = len(str(count - 1))
        ids = []
        for idx, point in enumerate(design_points(count, seed)):
            topo_id = f"{prefix}{idx:0{width}d}"
            topologies[topo_id] = {**build_spec(point, seed=seed * 1000 + idx), "name": topo_id}
            ids.append(topo_id)
        groups[{"R": "stage1", "L": "stage2"}[prefix]] = ids
    groups["all"] = list(topologies)
    header = ("# Generated by experiments/make_random_topologies.py; do not edit by hand.\n"
              f"# Design variable ranges: {RANGES}\n")
    body = {"defaults": {"neighbor_rule": {"method": "rssi", "cca_thresh_dbm": -82.0, "tx_power_dbm": 10.0,
                                           "path_loss_intercept": -46.67, "path_loss_exponent": 30.0,
                                           "min_distance_m": 0.5}},
            "groups": groups, "topologies": topologies}
    with open(OUT, "w") as handle:
        handle.write(header)
        yaml.safe_dump(body, handle, sort_keys=False, default_flow_style=None, width=120)
    print(f"wrote {len(topologies)} topologies to {OUT}")


if __name__ == "__main__":
    main()
